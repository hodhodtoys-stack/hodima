add_action( 'admin_notices', 'hodima_robots_physical_file_notice' );

function hodima_robots_physical_file_notice(): void {

	if ( ! current_user_can( 'manage_options' ) ) {
		return;
	}

	$screen = get_current_screen();
	if ( ! $screen || ! in_array( $screen->id, [ 'dashboard', 'options-reading', 'appearance_page_hodima-settings' ], true ) ) {
		return;
	}

	if ( ! is_file( ABSPATH . 'robots.txt' ) ) {
		return;
	}

	printf(
		'<div class="notice notice-warning"><p><strong>%1$s</strong> %2$s <a href="%3$s" target="_blank" rel="noopener">%4$s</a></p></div>',
		esc_html__( 'robots.txt:', 'hodima' ),
		esc_html__( 'یک فایل فیزیکی robots.txt در ریشه سایت وجود دارد و وب‌سرور همان را نمایش می‌دهد؛ قوانین هوشمند قالب (هماهنگ با سایت‌مپ، ووکامرس و تنظیمات ربات‌گیر) اعمال نمی‌شوند. برای استفاده از قوانین قالب، آن فایل را از هاست حذف کنید.', 'hodima' ),
		esc_url( home_url( '/robots.txt' ) ),
		esc_html__( 'مشاهده robots.txt فعلی', 'hodima' )
	);
}
