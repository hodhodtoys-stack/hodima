<?php
/**
 * کانال‌های تماس پنجره «پشتیبانی» هدر.
 * Path: hodima/inc/classes/enum-hodima-contact-channel.php
 *
 * قبلا کلید، برچسب، نام تنظیم و آیکون هر کانال در سه جای جدا بود
 * (hodima_contact_channels()، آرایه آیکون‌های header.php و شرط «تماس = tel:»).
 * حالا یک enum: همه ویژگی‌های هر کانال کنار هم و ترتیب نمایش = ترتیب case‌ها.
 * مقدار (value) همان کلید قبلی است (کلاس CSS: popup__link--{value}).
 */

declare(strict_types=1);

defined( 'ABSPATH' ) || exit;

enum Hodima_Contact_Channel: string {

	case Call     = 'call';
	case WhatsApp = 'whatsapp';
	case Rubika   = 'rubika';
	case Telegram = 'telegram';

	/** کلید تنظیمات قالب که مقدار کانال را نگه می‌دارد. */
	public function setting(): string {
		return match ( $this ) {
			self::Call     => 'phone',
			self::WhatsApp => 'whatsapp_url',
			self::Rubika   => 'rubika_url',
			self::Telegram => 'telegram_url',
		};
	}

	public function label(): string {
		return match ( $this ) {
			self::Call     => 'تماس تلفنی',
			self::WhatsApp => 'واتس‌اپ',
			self::Rubika   => 'روبیکا',
			self::Telegram => 'تلگرام',
		};
	}

	/** لینک بیرونی (پیام‌رسان) در زبانه جدید باز می‌شود؛ تماس تلفنی نه. */
	public function is_external(): bool {
		return self::Call !== $this;
	}

	/**
	 * پروتکل‌های مجاز لینک (برای esc_url).
	 *
	 * @return list<string>
	 */
	public function protocols(): array {
		return $this->is_external() ? [ 'https', 'http' ] : [ 'tel' ];
	}

	/** آدرس لینک از مقدار تنظیم (شماره تلفن → tel:). */
	public function url( string $value ): string {
		return self::Call === $this ? 'tel:' . $value : $value;
	}

	/** متن کامل لینک برای صفحه‌خوان. */
	public function aria( string $value ): string {
		return self::Call === $this ? 'تماس تلفنی با شماره ' . $value : 'ارتباط از طریق ' . $this->label();
	}

	/** محتوای SVG آیکون (viewBox 0 0 24 24؛ ثابت، بدون ورودی کاربر). */
	public function icon(): string {
		return match ( $this ) {
			self::Call     => '<path d="M6.62 10.79c1.44 2.83 3.76 5.14 6.59 6.59l2.2-2.2c.27-.27.67-.36 1.02-.24 1.12.37 2.33.57 3.57.57.55 0 1 .45 1 1V20c0 .55-.45 1-1 1-9.39 0-17-7.61-17-17 0-.55.45-1 1-1h3.5c.55 0 1 .45 1 1 0 1.25.2 2.45.57 3.57.11.35.03.74-.25 1.02l-2.2 2.2z"/>',
			self::WhatsApp => '<path d="M12 2a10 10 0 0 0-8.66 15l-1.3 4.76 4.87-1.28A10 10 0 1 0 12 2zm5.2 14.1c-.22.62-1.28 1.18-1.77 1.23-.47.05-.92.22-3.09-.64-2.61-1.03-4.27-3.7-4.4-3.87-.13-.17-1.05-1.4-1.05-2.67 0-1.27.66-1.9.9-2.16.23-.26.5-.32.67-.32h.48c.15 0 .36-.06.56.43.22.5.73 1.77.8 1.9.06.13.1.28.02.45-.08.17-.13.28-.26.43l-.38.45c-.13.13-.26.27-.11.53.15.26.67 1.1 1.44 1.78.99.88 1.82 1.15 2.08 1.28.26.13.41.11.56-.07.15-.17.65-.75.82-1.01.17-.26.34-.22.58-.13.24.09 1.5.71 1.76.84.26.13.43.19.5.3.06.1.06.62-.16 1.24z"/>',
			self::Rubika   => '<path d="M20 2H4A2 2 0 0 0 2 4v18l4-4h14a2 2 0 0 0 2-2V4a2 2 0 0 0-2-2z"/>',
			self::Telegram => '<path d="M11.944 0A12 12 0 0 0 0 12a12 12 0 0 0 12 12 12 12 0 0 0 12-12A12 12 0 0 0 12 0a12 12 0 0 0-.056 0zm4.962 7.224c.1-.002.321.023.465.14a.506.506 0 0 1 .171.325c.016.093.036.306.02.472-.18 1.898-.962 6.502-1.36 8.627-.168.9-.499 1.201-.82 1.23-.696.065-1.225-.46-1.9-.902-1.056-.693-1.653-1.124-2.678-1.8-1.185-.78-.417-1.21.258-1.91.177-.184 3.247-2.977 3.307-3.23.007-.032.014-.15-.056-.212s-.174-.041-.249-.024c-.106.024-1.793 1.14-5.061 3.345-.48.33-.913.49-1.302.48-.428-.008-1.252-.241-1.865-.44-.752-.245-1.349-.374-1.297-.789.027-.216.325-.437.893-.663 3.498-1.524 5.83-2.529 6.998-3.014 3.332-1.386 4.025-1.627 4.476-1.635z"/>',
		};
	}
}
