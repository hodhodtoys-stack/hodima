/**
 * راهنمای کامل یک ایراد خزنده برای کارت «کارها» (SEO 3.6.9): چه دیدیم، لازم است؟، گام‌ها، از کجا بفهمم، چرا مهم است.
 * `$detail` جزئیات خود ایراد (عدد، کد)؛ `$level` سطح همین ایراد برای همین صفحه (ممکن است از کاتالوگ فرق کند، مثلا no_meta).
 *
 * @return array{seen: string, need: string, steps: list<string>, verify: string, why: string}|null
 */
function hodima_seo_advisor_issue_guide( string $code, string $detail = '', string $where = '', string $level = '' ): ?array {

	$record = hodima_seo_advisor_issue_catalog()[ $code ] ?? null;

	if ( null === $record ) {
		return null;
	}

	$detail = trim( $detail, " \t\n\r\0\x0B." );
	$seen   = '' === $detail && isset( $record['seen_empty'] ) ? $record['seen_empty'] : $record['seen'];
	$where  = '' !== $where ? $where : 'ویرایش صفحه';

	return [
		'seen'   => trim( (string) preg_replace( '/\s*\(\)|\s{2,}/u', ' ', str_replace( '{d}', $detail, $seen ) ) ),
		'need'   => hodima_seo_advisor_issue_need( '' !== $level ? $level : $record['level'] ),
		'steps'  => array_map( static fn( string $step ): string => str_replace( '{where}', $where, $step ), $record['steps'] ),
		'verify' => hodima_seo_advisor_issue_verify_text( $code ),
		'why'    => $record['why'],
	];
}

/** برچسب «لازم است؟» (must/rec/opt)؛ نمایش در «کارها» (advisor-overview-view.php). */
const HODIMA_SEO_ADVISOR_NEED_LABELS = [
	'must' => 'باید رفع شود',
	'rec'  => 'بهتر است رفع شود',
	'opt'  => 'اختیاری',
];

/** «لازم است؟» از سطح: قرمز = باید، کهربایی = بهتر است، اطلاع = فقط اگر لازم بدانید. */
function hodima_seo_advisor_issue_need( string $level ): string {
	return match ( $level ) {
		'bad'   => 'must',
		'warn'  => 'rec',
		default => 'opt',
	};
}

/** «از کجا بفهمم درست شد؟» از نوع سنجش «انجام دادم» (advisor-marks.php). */
function hodima_seo_advisor_issue_verify_text( string $code ): string {

	if ( in_array( $code, HODIMA_SEO_ADVISOR_MARK_LIVE_CODES, true ) || in_array( $code, [ 'broken', 'server_error' ], true ) ) {
		return 'بعد از ذخیره «انجام دادم» را بزنید؛ دستار همان لحظه صفحه را از سایت می‌خواند و نتیجه را می‌گوید.';
	}

	if ( in_array( $code, HODIMA_SEO_ADVISOR_MARK_RECRAWL_CODES, true ) ) {
		return 'بعد از ذخیره «انجام دادم» را بزنید؛ دستار همین صفحه را همان لحظه دوباره می‌خواند (چند ثانیه).';
	}

	return '«انجام دادم» را بزنید؛ بعد از خزش شبانه (یا «خزش همین حالا» در تب «خزش و داده») اگر درست شده باشد از فهرست می‌رود.';
}

/**
 * دستور یک ایراد با نام «ویرایش» همان نوع صفحه (مثلا «ویرایش محصول»). `$where` خالی = «ویرایش صفحه».
 */
function hodima_seo_advisor_issue_fix( string $code, string $where = '' ): string {

	$fix = (string) ( hodima_seo_advisor_issue_catalog()[ $code ]['fix'] ?? '' );

	return '' === $fix ? '' : str_replace( '{where}', '' !== $where ? $where : 'ویرایش صفحه', $fix );
}

/**
 * نام «ویرایش» نوع صفحه از برچسب‌های خود وردپرس/ووکامرس (مثلا «ویرایش محصول»، «ویرایش دسته»)؛ صفحه اصلی «ویرایش صفحه اصلی».
 * `$kind` نوع نوشته یا طبقه‌بندی (ستون kind جدول آدرس‌ها)؛ خالی = از روتر پیدا می‌شود. بی‌نتیجه = رشته خالی (دستور «ویرایش صفحه» می‌گوید).
 */
function hodima_seo_advisor_issue_where( string $path, string $kind = '' ): string {

	if ( '/' === $path ) {
		return 'ویرایش صفحه اصلی';
	}

	if ( '' === $kind ) {
		$kind = hodima_seo_advisor_classify( $path )['kind'];
	}

	if ( '' !== $kind && post_type_exists( $kind ) ) {
		$object = get_post_type_object( $kind );
		return null !== $object && '' !== (string) $object->labels->edit_item ? (string) $object->labels->edit_item : '';
	}

	if ( '' !== $kind && taxonomy_exists( $kind ) ) {
		$object = get_taxonomy( $kind );
		return null !== $object && '' !== (string) $object->labels->edit_item ? (string) $object->labels->edit_item : '';
	}

	return '';
}
