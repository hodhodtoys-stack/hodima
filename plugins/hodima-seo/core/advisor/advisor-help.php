/**
 * دکمه «؟» کنار یک اصطلاح (popover بومی؛ Esc و کلیک بیرون می‌بندد). HTML امن‌شده؛ اصطلاح ناشناخته = رشته خالی.
 */
function hodima_seo_advisor_help( string $key ): string {

	static $n = 0;
	$entry    = hodima_seo_advisor_glossary()[ $key ] ?? null;

	if ( null === $entry ) {
		return '';
	}

	$id = 'hdsa-help-' . ( ++$n );

	return sprintf(
		'<button type="button" class="hodima-advisor-help" popovertarget="%1$s" aria-label="%2$s">؟</button><span id="%1$s" popover class="hodima-advisor-help__pop"><strong>%3$s</strong> %4$s</span>',
		esc_attr( $id ),
		esc_attr( sprintf( '«%s» یعنی چه؟', $entry[0] ) ),
		esc_html( $entry[0] ),
		esc_html( $entry[1] )
	);
}

