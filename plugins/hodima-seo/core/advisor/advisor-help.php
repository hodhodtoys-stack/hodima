/**
 * فهرست جمع‌شونده «اصطلاح‌ها به زبان ساده» (پایین هر تب صفحه دستار سئو).
 */
function hodima_seo_advisor_render_glossary(): void {

	echo '<details class="hds-card hodima-advisor__glossary"><summary>اصطلاح‌ها به زبان ساده</summary><dl>';

	foreach ( hodima_seo_advisor_glossary() as [ $term, $text ] ) {
		printf( '<div><dt>%1$s</dt><dd>%2$s</dd></div>', esc_html( $term ), esc_html( $text ) );
	}

	echo '</dl></details>';
}
